// A calendar date as text. This file imports nothing, thus the planning and pipeline code can use it
// in a browser page with no other package.

/** A real calendar date in the form YYYY-MM-DD. It is a local date: it has no time and no time zone. */
export function isRealDate(text: string): boolean {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(text);
  if (!m) return false;
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const date = new Date(Date.UTC(y, mo - 1, d));
  return date.getUTCFullYear() === y && date.getUTCMonth() === mo - 1 && date.getUTCDate() === d;
}
