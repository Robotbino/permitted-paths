"""Copies the reference application of the Practical Architecture Studio into the course page.

A page that opens from file:// cannot read files, thus the page needs a copy of them as data.
This tool makes that copy from examples/personal-finance:

  js/data/studio-files.js   each source file that levels.json names, with its level and its role
  js/data/studio-runs.js    recordings/runs.json: what the real code did in each scenario
  index.html                the code blocks that have data-file="examples/..." (the text with no JavaScript)

Run it after each change to examples/personal-finance:

  python examples/tools/sync-studio.py           write the files
  python examples/tools/sync-studio.py --check   write nothing; exit 1 if a file is not current

The tool refuses to copy a secret or a path of a computer: this repository is public.
"""
import hashlib
import html
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
APP = os.path.join(ROOT, 'examples', 'personal-finance')
FILES_JS = os.path.join(ROOT, 'js', 'data', 'studio-files.js')
RUNS_JS = os.path.join(ROOT, 'js', 'data', 'studio-runs.js')
PAGE = os.path.join(ROOT, 'index.html')

# Text that must not be in a public file: a drive path, a home folder, an API key.
FORBIDDEN = re.compile(r'[A-Za-z]:\\\\?Users|/Users/|/home/[a-z]|sk-ant-[A-Za-z0-9]')
NEVER = ('.env', 'data/', 'node_modules/', 'web/dist/')


def read(path):
    with io.open(path, encoding='utf-8', newline='') as f:
        return f.read().replace('\r\n', '\n')


def safe(name, text):
    if name == '.env' or name.startswith(NEVER):
        sys.exit('FAIL  ' + name + ' must not be copied.')
    found = FORBIDDEN.search(text)
    if found:
        sys.exit('FAIL  ' + name + ' contains text that must not be public: ' + found.group(0))
    return text


def build():
    levels = json.loads(read(os.path.join(APP, 'levels.json')))
    files = {}
    for name in sorted(levels['files']):
        entry = levels['files'][name]
        files[name] = {
            'level': entry['level'],
            'modified': entry.get('modified', []),
            'role': entry['role'],
            'text': safe(name, read(os.path.join(APP, *name.split('/'))).rstrip('\n')),
        }
    runs = json.loads(safe('recordings/runs.json', read(os.path.join(APP, 'recordings', 'runs.json'))))

    # One hash over the two parts. The two generated files carry it; tests.html compares them.
    digest = hashlib.sha256()
    digest.update(json.dumps(files, sort_keys=True, ensure_ascii=True).encode())
    digest.update(json.dumps(runs, sort_keys=True, ensure_ascii=True).encode())
    stamp = digest.hexdigest()[:16]

    head = '/* GENERATED by examples/tools/sync-studio.py from examples/personal-finance. Do not edit. */\n'
    files_js = head + 'GE.data.studioFiles = ' + json.dumps({'hash': stamp, 'levels': levels['levels'], 'files': files}, ensure_ascii=True, separators=(',', ':')) + ';\n'
    runs_js = head + 'GE.data.studioRuns = ' + json.dumps(dict(runs, hash=stamp), ensure_ascii=True, separators=(',', ':')) + ';\n'
    return files, files_js, runs_js


BLOCK = re.compile(r'(<div class="pcode" data-lab="copy" data-keep data-file=")(examples/personal-finance/[^"]+)(">\s*<pre><code>)(.*?)(</code></pre>)', re.S)


def page_with(files):
    page = read(PAGE)
    count = [0]

    def put(match):
        name = match.group(2)[len('examples/personal-finance/'):]
        if name not in files:
            sys.exit('FAIL  The page names a file that levels.json does not name: ' + name)
        count[0] += 1
        return match.group(1) + match.group(2) + match.group(3) + html.escape(files[name]['text'], quote=False) + match.group(5)

    return BLOCK.sub(put, page), count[0]


def main():
    check = '--check' in sys.argv
    files, files_js, runs_js = build()
    page, blocks = page_with(files)
    stale = []
    for path, text in ((FILES_JS, files_js), (RUNS_JS, runs_js), (PAGE, page)):
        current = read(path) if os.path.exists(path) else None
        if current != text:
            stale.append(os.path.relpath(path, ROOT).replace(os.sep, '/'))
            if not check:
                with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(text)
    summary = '%d files, %d page blocks' % (len(files), blocks)
    if check and stale:
        sys.exit('FAIL  not current: ' + ', '.join(stale) + '. Run: python examples/tools/sync-studio.py')
    print(('PASS  current: ' if check else 'Wrote ' + (', '.join(stale) or 'nothing (all current)') + ': ') + summary)


if __name__ == '__main__':
    main()
